#!/usr/bin/env python3
"""Generate scripts/localeprobe.lua for a GUI test copy: the probe asks the client to translate every locale key the
mod's Lua code uses (literal keys and the expanded dynamic families), every key in locale/en, and the localised name of
every rts-* prototype, then logs "[rts] locale probe: N strings, M not translated: ..." (on_string_translated reports
translated = false for an unknown key). Usage: gen.py <mod dir> <out lua file>"""
import glob, os, re, sys
mod, out = sys.argv[1], sys.argv[2]
keys = set()
sec = ""
for f in glob.glob(os.path.join(mod, "locale", "en", "*.cfg")):
    for line in open(f, encoding="utf-8"):
        s = line.strip()
        if not s or s.startswith(("#", ";")): continue
        m = re.match(r"^\[([^\]]+)\]$", s)
        if m: sec = m.group(1); continue
        if "=" in s: keys.add(sec + "." + s.split("=", 1)[0])
SECTIONS = {"rts", "controls", "entity-name", "item-name", "recipe-name", "technology-name", "technology-description",
            "entity-description", "item-description", "equipment-name", "mod-name", "mod-description"}
for f in glob.glob(os.path.join(mod, "**", "*.lua"), recursive=True):
    for line in open(f, encoding="utf-8"):
        code = line.split("--")[0]
        for m in re.finditer(r'"([a-z][a-z0-9-]*)\.([A-Za-z0-9_\-]+)"(?!\s*\.\.)', code):
            if m.group(1) in SECTIONS: keys.add(m.group(1) + "." + m.group(2))
# dynamic families (scripts/lobby.lua, techgui.lua, abilities.lua, hud.lua, mapgen.lua, match.lua)
fam = {"rts.difficulty-": ["easy", "normal", "hard"], "rts.map-": ["chokes", "open"],
       "rts.size-": ["small", "medium", "large", "legacy"], "rts.results-": ["victory", "defeat", "draw"],
       "rts.match-": ["victory", "defeat", "draw"], "rts.ability-": ["stim", "shield", "scanner", "artillery", "overcharge"],
       "rts.tech-tier-": ["1", "2"], "rts.patch-kind-": ["main", "natural", "middle"],
       "rts.tech-status-": ["available", "disabled", "done", "locked", "queued", "researching"],
       "rts.help-": [str(i) for i in range(1, 11)],
       "item-name.": ["iron-ore", "copper-ore", "stone", "coal", "iron-plate", "copper-plate", "steel-plate",
                      "electronic-circuit", "stone-brick", "iron-gear-wheel", "copper-cable"]}
for p, vals in fam.items():
    for v in vals: keys.add(p + v)
lines = ["-- Generated by tools/locale-probe/gen.py for a GUI test copy (not part of the mod).",
         "local events = require('scripts.events')", "local KEYS = {"]
for k in sorted(keys): lines.append('  "%s",' % k)
lines += ["}", r'''
local function proto_names()
  local out = {}
  for _, group in ipairs({"entity", "item", "recipe", "technology"}) do
    for name, p in pairs(prototypes[group]) do
      if string.sub(name, 1, 4) == "rts-" and not (p.hidden) then out[#out + 1] = {group .. " " .. name, p.localised_name} end
    end
  end
  return out
end

events.on(defines.events.on_string_translated, function(e)
  local s = storage.locale_probe
  if not (s and s.ids[e.id]) then return end
  local label = s.ids[e.id]
  s.ids[e.id] = nil
  s.done = s.done + 1
  if not e.translated then s.bad[#s.bad + 1] = label end
  if s.done == s.total then
    log(string.format("[rts] locale probe (%s): %d strings, %d not translated%s", tostring(s.locale), s.total, #s.bad,
      #s.bad > 0 and (": " .. table.concat(s.bad, ", ")) or ""))
  end
end)

events.on_nth_tick(120, function()
  if storage.locale_probe then return end
  local player = game.connected_players[1]
  if not player then return end
  local s = {ids = {}, bad = {}, done = 0, total = 0, locale = player.locale}
  storage.locale_probe = s
  local function ask(label, ls)
    local id = player.request_translation(ls)
    if id then s.ids[id] = label s.total = s.total + 1 end
  end
  for _, k in ipairs(KEYS) do ask(k, {k}) end
  for _, pn in ipairs(proto_names()) do ask(pn[1], pn[2]) end
  log(string.format("[rts] locale probe: requested %d translations for player %d (%s)", s.total, player.index, player.locale))
end)
''']
open(out, "w").write("\n".join(lines))
print("keys", len(keys))
